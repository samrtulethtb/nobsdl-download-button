    async function startJob(choice) {
      const token = ++state.token;
      state.busy = true;
      state.keepView = true;
      const jobPage = targetPage();
      const sourceUrl = state.target.url;
      const title = (state.info && state.info.title) || jobPage.name;
      const steps = el("ol", {class: "steps", "aria-label": t("Download progress")},
        ["Queue", "Download", "Process", "Ready"].map((label) => el("li", {}, [el("i", {"aria-hidden": "true"}), t(label)])));
      const bar = el("div", {class: "bar waiting"});
      const track = el("div", {class: "track", role: "progressbar", "aria-label": t("Download progress"), "aria-valuemin": "0", "aria-valuemax": "100"}, [bar]);
      const line = el("p", {class: "status-line", "aria-live": "polite"});
      const extra = el("div");
      show([header(title, choice.title + " · " + choice.format.toUpperCase()), el("div", {class: "body"}, [steps, track, line, extra]), footer()]);

      let phase = "requesting";
      let since = Date.now();
      let progress = null;
      let renderedPhase = null;
      const render = () => {
        const view = progressView(phase, progress, Math.floor((Date.now() - since) / 1000), jobPage.name.replace(/ (Shorts|playlist)$/, ""), choice.format);
        Array.from(steps.children).forEach((item, index) => {
          item.dataset.state = index < view.step || phase === "ready" ? "done" : index === view.step ? "current" : "pending";
        });
        if (renderedPhase !== phase) { bar.style.transition = "none"; void bar.offsetWidth; setTimeout(() => { bar.style.transition = ""; }, 50); }
        renderedPhase = phase;
        bar.className = "bar " + view.mode;
        bar.style.width = view.mode === "measured" ? (view.fraction * 100).toFixed(1) + "%" : view.mode === "waiting" ? "" : "100%";
        if (view.mode === "measured" || view.mode === "done") track.setAttribute("aria-valuenow", String(view.mode === "done" ? 100 : Math.floor(view.fraction * 100)));
        else track.removeAttribute("aria-valuenow");
        line.textContent = view.text;
        if (phase === "ready") setDockLabel(t("✓ Saved"), 1);
        else if (view.mode === "measured") setDockLabel(Math.floor(view.fraction * 100) + "%", view.fraction);
        else setDockLabel("…", null);
      };
      const setPhase = (next, nextProgress) => {
        if (PHASE_ORDER.indexOf(next) < PHASE_ORDER.indexOf(phase)) next = phase;
        if (next !== phase) { phase = next; since = Date.now(); }
        if (nextProgress && typeof nextProgress === "object") {
          const prev = progress && typeof progress.fraction === "number" ? progress.fraction : null;
          progress = Object.assign({}, nextProgress);
          if (prev !== null && typeof progress.fraction === "number" && progress.fraction < prev) progress.fraction = prev;
        }
        render();
      };
      render();
      const ticker = setInterval(() => { if (token === state.token) render(); else clearInterval(ticker); }, 1000);

      try {
        const job = await apiGet(downloadParams(choice, sourceUrl), 30000);
        if (token !== state.token) return;
        const statusPath = safeStatusPath(job.status_url);
        if (!statusPath) throw Object.assign(new Error(t("NoBsDL returned an unexpected answer. Try again.")), {status: 0});
        const deadline = Date.now() + POLL_DEADLINE_MS;
        let misses = 0;
        while (token === state.token && Date.now() < deadline) {
          let status;
          try {
            status = await apiGet(statusPath, 20000);
            misses = 0;
          } catch (error) {
            // A dropped poll is not a failed job; the server keeps working.
            if (!error.retryable || ++misses >= 5) throw error;
            await new Promise((r) => setTimeout(r, 1000 * misses));
            continue;
          }
          if (token !== state.token) return;
          if (status.status === "ready") {
            const fileUrl = safeFileUrl(status.direct_url);
            if (!fileUrl) throw Object.assign(new Error(t("NoBsDL returned an unexpected file link.")), {status: 0});
            setPhase("ready", null);
            state.busy = false;
            saveFile(fileUrl, extra);
            return;
          }
          setPhase(status.phase || "queued", status.progress || null);
          await new Promise((r) => setTimeout(r, POLL_INTERVAL_MS));
        }
        if (token === state.token) throw Object.assign(new Error(t("This is taking unusually long. Try again or open it on NoBsDL.")), {status: 0});
      } catch (error) {
        clearInterval(ticker);
        if (token !== state.token) return;
        state.busy = false;
        setDockLabel("", null);
        if (!state.open) { state.open = true; renderDock(); }   // surface the failure
        showError(error, error && error.refreshFormats ? () => { state.choices = null; loadFormats(); } : () => startJob(choice));
      } finally {
        if (phase === "ready") clearInterval(ticker);
      }
    }

    // The file response is Content-Disposition: attachment, so navigating to

  // ── Feeds (2.2.0) ──────────────────────────────────────────────────────
  // On feeds the page URL stays the same while clips scroll by (TikTok For
  // You, X/Reddit/Bluesky/9GAG timelines, Instagram/Facebook feeds), so the
  // URL alone can't say what to download. There the button appears while a
  // real video is on screen, and on click the clip is read from the page
  // itself: the most visible (playing first) video, then the permalink of
  // the post around it. Only the DOM is read; nothing is sent until click.
  // YouTube and the grid-style sites are not listed: opening a video there
  // changes the URL, which pageFor already covers.
  const FEED_HOSTS = Object.freeze([
    ["tiktok.com", "tiktok", "TikTok", "/tiktok-downloader", VIDEO_AUDIO],
    ["x.com", "twitter", "X / Twitter", "/x-downloader", VIDEO_AUDIO],
    ["twitter.com", "twitter", "X / Twitter", "/x-downloader", VIDEO_AUDIO],
    ["reddit.com", "reddit", "Reddit", "/reddit-downloader", VIDEO_AUDIO],
    ["instagram.com", "instagram", "Instagram", "/instagram-downloader", VIDEO_AUDIO],
    ["facebook.com", "facebook", "Facebook", "/facebook-downloader", VIDEO_AUDIO],
    ["bsky.app", "bluesky", "Bluesky", "/universal-downloader", VIDEO_AUDIO],
    ["9gag.com", "9gag", "9GAG", "/universal-downloader", VIDEO_AUDIO],
    ["soundcloud.com", "soundcloud", "SoundCloud", "/soundcloud-to-mp3", AUDIO_ONLY],
  ]);
  const FEED_MIN_WIDTH = 200;
  const FEED_MIN_HEIGHT = 150;

  function feedPageFor(input) {
    let url;
    try { url = input instanceof URL ? input : new URL(String(input || "")); } catch (_) { return null; }
    if ((url.protocol !== "http:" && url.protocol !== "https:") || pageFor(url)) return null;
    const host = url.hostname.toLowerCase().replace(/\.$/, "");
    const entry = FEED_HOSTS.find(([suffix]) => hostIs(host, suffix));
    return entry ? page(entry[1], entry[2], "feed", entry[3], entry[4], {feed: true}) : null;
  }

  // One key per media post, so two links to the same post (timestamp,
  // "/photo/1", "/analytics"...) count once and two different posts in one
  // container count as ambiguous.
  function mediaLink(href, base, platform) {
    let url;
    try { url = new URL(href, base); } catch (_) { return null; }
    const matched = pageFor(url);
    if (!matched || matched.platform !== platform || matched.workflow === "playlist") return null;
    const path = url.pathname.replace(/\/+$/, "");
    let m;
    if (platform === "twitter" && (m = path.match(/^(\/[^/]+\/status\/\d+)/))) return {key: "x:" + path.split("/")[3], href: "https://x.com" + m[1]};
    if (platform === "reddit" && (m = path.match(/\/comments\/([A-Za-z0-9]+)/))) return {key: "r:" + m[1], href: url.origin + path};
    if (platform === "instagram" && (m = path.match(/^\/(?:p|reels?|tv)\/([A-Za-z0-9_-]+)/))) return {key: "ig:" + m[1], href: url.origin + path};
    if (platform === "facebook" && /^\/watch$/i.test(path)) return {key: "fb:" + url.searchParams.get("v"), href: url.origin + "/watch/?v=" + encodeURIComponent(url.searchParams.get("v"))};
    return {key: url.hostname.replace(/^(?:www|m|mobile)\./, "") + path, href: url.origin + path};
  }

  function parentAcrossShadow(node) {
    if (node.parentElement) return node.parentElement;
    const root = node.getRootNode && node.getRootNode();
    return root && root.host ? root.host : null;
  }

  // Walks up from the video to the first container that links to exactly one
  // media post. A container that links to two different posts means we
  // climbed past the post: no guess is made.
  function permalinkAround(el, platform, base) {
    let node = el;
    for (let depth = 0; depth < 16 && node && node.nodeType === 1; depth++, node = parentAcrossShadow(node)) {
      const found = new Map();
      if (node.tagName === "SHREDDIT-POST" && node.getAttribute("permalink")) {
        const link = mediaLink(node.getAttribute("permalink"), base, platform);
        if (link) return link.href;
      }
      const anchors = node.querySelectorAll("a[href]");
      if (anchors.length > 400) return null;   // far past a single post
      for (const a of anchors) {
        const link = mediaLink(a.getAttribute("href"), base, platform);
        if (link) found.set(link.key, link.href);
        if (found.size > 1) return null;
      }
      if (found.size === 1) return found.values().next().value;
      if (node.tagName === "BODY") return null;
    }
    return null;
  }

  // TikTok's desktop feed carries no per-clip link, but every player sits in
  // div#xgwrapper-<n>-<videoId> next to the author's avatar link
  // (checked on the live For You page, 2026-10-06).
  function tiktokFeedUrl(video) {
    let node = video;
    let id = "";
    for (let i = 0; i < 6 && node && !id; i++, node = node.parentElement) {
      const m = /^xgwrapper-\d+-(\d{15,20})$/.exec(node.id || "");
      if (m) id = m[1];
    }
    if (!id) return null;
    for (let i = 0; i < 12 && node; i++, node = node.parentElement) {
      const a = node.querySelector('a[data-e2e="video-author-avatar"][href^="/@"]');
      if (a) {
        const author = a.getAttribute("href").slice(2).split(/[/?#]/)[0];
        return /^[\w.-]{1,64}$/.test(author) ? "https://www.tiktok.com/@" + author + "/video/" + id : null;
      }
    }
    return null;
  }

  // TikTok's mobile web feed keeps the clip id only in the app's React
  // props. Userscript managers that run scripts beside the page (not in an
  // isolated world) can read them; otherwise the panel asks for the link.
  function tiktokMobileUrl(video) {
    const slide = video.closest('[data-e2e="video-slide-active"]');
    if (!slide) return null;
    try {
      const raw = slide.wrappedJSObject || slide;
      const key = Object.keys(raw).find((k) => k.startsWith("__reactFiber$"));
      let fiber = key ? raw[key] : null;
      let id = "";
      for (let i = 0; i < 12 && fiber && !id; i++, fiber = fiber.return) {
        const props = fiber.memoizedProps;
        if (props && /^\d{17,20}$/.test(String(props.id || ""))) id = String(props.id);
      }
      const a = slide.querySelector('a[href^="/@"]');
      const author = a ? a.getAttribute("href").slice(2).split(/[/?#]/)[0] : "";
      return id && /^[\w.-]{1,64}$/.test(author) ? "https://www.tiktok.com/@" + author + "/video/" + id : null;
    } catch (_) {
      return null;
    }
  }

  function feedMedia(doc, platform) {
    const view = doc.defaultView;
    const vw = view.innerWidth;
    const vh = view.innerHeight;
    const nodes = Array.from(doc.querySelectorAll("video"));
    // Reddit renders its player in a web component; its box is the player.
    if (platform === "reddit") nodes.push(...doc.querySelectorAll("shreddit-player, shreddit-player-2"));
    return nodes.map((el) => {
      const r = el.getBoundingClientRect();
      const area = Math.max(0, Math.min(r.right, vw) - Math.max(r.left, 0)) * Math.max(0, Math.min(r.bottom, vh) - Math.max(r.top, 0));
      return {el, r, area, playing: el.tagName === "VIDEO" && !el.paused};
    }).filter((m) => m.r.width >= FEED_MIN_WIDTH && m.r.height >= FEED_MIN_HEIGHT && m.area >= 0.4 * m.r.width * m.r.height)
      .sort((a, b) => (b.playing - a.playing) || (b.area - a.area));
  }

  // → {url, el} for the clip to download, {url: null, el, askLink: true} when
  // a clip is on screen but its link isn't readable, or null.
  function findFeedTarget(platform, doc) {
    const base = doc.location.href;
    if (platform === "soundcloud") {
      const a = doc.querySelector("a.playbackSoundBadge__titleLink[href]");
      const link = a && mediaLink(a.getAttribute("href"), base, platform);
      return link ? {url: link.href, el: a} : null;
    }
    for (const m of feedMedia(doc, platform).slice(0, 4)) {
      if (platform === "tiktok") {
        const url = tiktokFeedUrl(m.el) || tiktokMobileUrl(m.el);
        if (url) return {url, el: m.el};
        if (m.el.closest('[data-e2e="video-slide-active"]')) return {url: null, el: m.el, askLink: true};
        continue;
      }
      const url = permalinkAround(m.el, platform, base);
      if (url) return {url, el: m.el};
    }
    return null;
  }

  // ── Buttons on videos (2.4.0) ──────────────────────────────────────────
  // With a mouse, a round button appears on the video or thumbnail under the
  // pointer and opens the panel for that exact clip: a thumbnail's own link,
  // the post around a video in a feed (X, Reddit, Instagram, Facebook,
  // Bluesky, 9GAG, TikTok), or the page itself for its main player. Only the
  // page is read; nothing is sent until the button is clicked.
  const INLINE_MIN_WIDTH = 120;
  const INLINE_MIN_HEIGHT = 66;
  const THUMB_PLATFORMS = new Set(["youtube", "tiktok", "twitch", "dailymotion", "rutube", "okru", "odysee", "streamable", "bilibili"]);
  const POST_PLATFORMS = new Set(["twitter", "reddit", "instagram", "facebook", "bluesky", "9gag"]);

  // YouTube's main player counts before its <video> has loaded (a cued
  // video keeps the element off to the side).
  const YOUTUBE_MAIN_PLAYERS = new Set(["movie_player", "shorts-player"]);

  function isVideoNode(node) {
    return node.tagName === "VIDEO" || node.tagName === "SHREDDIT-PLAYER" || node.tagName === "SHREDDIT-PLAYER-2"
      || YOUTUBE_MAIN_PLAYERS.has(node.id);
  }

  function bigEnough(rect) {
    return rect.width >= INLINE_MIN_WIDTH && rect.height >= INLINE_MIN_HEIGHT;
  }

  // The single video a page is about: a YouTube watch link keeps only its
  // video id (no playlist, tracking or start-time parameters).
  function singleVideoUrl(href) {
    let url;
    try { url = new URL(href); } catch (_) { return null; }
    const matched = pageFor(url);
    if (!matched) return null;
    const v = url.searchParams.get("v");
    if (matched.platform === "youtube" && url.pathname.toLowerCase() === "/watch" && validId(v)) return "https://www.youtube.com/watch?v=" + v;
    if (matched.platform === "bilibili") {
      // Only the part number matters; feed links add tracking ids.
      const part = url.searchParams.get("p");
      return url.origin + url.pathname + (/^\d{1,4}$/.test(part || "") ? "?p=" + part : "");
    }
    return matched.workflow === "playlist" ? null : url.href;
  }

  // A link to one supported video that shows a picture (or preview) of it.
  function thumbnailLink(node, base) {
    const a = node.closest ? node.closest("a[href]") : null;
    if (!a || !a.querySelector("img, yt-image, picture, video")) return null;
    let url;
    try { url = new URL(a.getAttribute("href"), base); } catch (_) { return null; }
    url.hash = "";
    const matched = pageFor(url);
    const reel = matched && matched.platform === "instagram" && /^\/reels?\//i.test(url.pathname);
    if (!matched || !(THUMB_PLATFORMS.has(matched.platform) || reel)) return null;
    const href = singleVideoUrl(url.href);
    return href ? {url: href, el: a} : null;
  }

  function videoTargetUrl(node, doc) {
    const base = doc.location.href;
    const here = pageFor(base);
    const platform = (here || feedPageFor(base) || {}).platform;
    let url = null;
    if (YOUTUBE_MAIN_PLAYERS.has(node.id) || (platform === "youtube" && node.closest && node.closest("#movie_player, #shorts-player"))) {
      return here && here.platform === "youtube" ? singleVideoUrl(base) : null;
    }
    if (platform === "tiktok") url = tiktokFeedUrl(node) || tiktokMobileUrl(node);
    else if (POST_PLATFORMS.has(platform)) url = permalinkAround(node, platform, base);
    // Otherwise only the page's main (largest visible) player is the page.
    if (!url && here) {
      const main = feedMedia(doc, platform)[0];
      if (main && main.el === node) url = singleVideoUrl(base);
    }
    return url;
  }

  // What the button under the pointer is for: {url, rect} or null. `stack`
  // is document.elementsFromPoint() at the pointer, topmost first: the
  // topmost thumbnail or video that resolves to a clip wins, so a page
  // element hidden under the player never does. A preview playing over a
  // thumbnail resolves to nothing itself and lets the thumbnail below win.
  function inlineTarget(stack, doc, cache) {
    const base = doc.location.href;
    for (const node of stack.slice(0, 40)) {
      if (isVideoNode(node)) {
        const rect = node.getBoundingClientRect();
        if (!bigEnough(rect)) continue;
        const hit = cache && cache.get(node);
        let url;
        if (hit && Date.now() - hit.at < 2000) url = hit.url;
        else {
          url = videoTargetUrl(node, doc);
          if (cache) cache.set(node, {url, at: Date.now()});
        }
        if (url) return {url, rect};
        continue;
      }
      const thumb = thumbnailLink(node, base);
      if (!thumb) continue;
      let rect = thumb.el.getBoundingClientRect();
      if (!bigEnough(rect)) {
        const picture = thumb.el.querySelector("img, yt-image, picture, video");
        rect = picture ? picture.getBoundingClientRect() : rect;
      }
      if (bigEnough(rect)) return {url: thumb.url, rect};
    }
    return null;
  }

  function sourceUrlFor(currentUrl, matchedPage) {
    if (matchedPage.workflow === "playlist" && matchedPage.listId) {
      const normalized = new URL("https://www.youtube.com/playlist");
      normalized.searchParams.set("list", matchedPage.listId);
      return normalized.href;
    }
    return new URL(currentUrl).href;
  }

  function targetUrl(matchedPage, currentUrl, output) {
    if (!matchedPage || !matchedPage.outputs.includes(output)) return null;
    let route = matchedPage.route;
    if (matchedPage.platform === "youtube" && matchedPage.workflow === "single") {
      route = output === "mp3" ? "/youtube-to-mp3" : "/youtube-downloader";
    }
    const target = new URL(route, NOBSDL_ORIGIN);
    target.searchParams.set("url", sourceUrlFor(currentUrl, matchedPage));
    if (matchedPage.outputs === VIDEO_AUDIO && !(matchedPage.platform === "youtube" && matchedPage.workflow === "single")) {
      target.searchParams.set("prefer", output);
    } else if (matchedPage.route === "/universal-downloader" && output === "mp3") {
      target.searchParams.set("prefer", "mp3");
    }
    return target.href;
  }


  // ── Formats ────────────────────────────────────────────────────────────
  // One uniform list from /api/video-info (same contract as the NoBsDL
  // browser extension): YouTube exposes curated choice ids, other platforms
  // free/Supporter format dictionaries. `locked` = Supporter tier without an
  // active Supporter session. Sizes are NoBsDL's own estimates.
  function positiveNumber(value) {
    const n = Number(value);
    return Number.isFinite(n) && n > 0 ? n : null;
  }

  function heightFromLabel(label) {
    const m = String(label || "").match(/(\d{3,4})p/);
    return m ? Number(m[1]) : 0;
  }

  function normalizeChoices(data) {
    const premium = !!(data && data.is_supporter);
    const out = [];
    const yt = data && data.youtube_video_choices;
    if (yt && (Array.isArray(yt.free) || Array.isArray(yt.supporter))) {
      const addVideo = (c, supporterList) => {
        if (!c || !c.choice_id) return;
        out.push({
          key: "v:" + c.choice_id, family: "video", format: "mp4", ytChoice: String(c.choice_id),
          title: c.height + "p", fps: Number(c.fps) > 30 ? Math.round(Number(c.fps)) : 0,
          height: Number(c.height) || 0, sizeMb: positiveNumber(c.size_mb),
          locked: !premium && (supporterList || c.tier === "supporter"),
        });
      };
      (yt.free || []).forEach((c) => addVideo(c, false));
      (yt.supporter || []).forEach((c) => addVideo(c, true));
      (data.youtube_mp3_choices || []).forEach((c) => {
        if (!c || !c.choice_id) return;
        out.push({
          key: "a:" + c.choice_id, family: "audio", format: "mp3", ytChoice: String(c.choice_id),
          title: c.bitrate_kbps + " kbps", bitrate: Number(c.bitrate_kbps) || 0,
          sizeMb: positiveNumber(c.size_mb), locked: !premium && c.tier === "supporter",
        });
      });
    } else {
      const addVideos = (entries, supporterList) => Object.entries(entries || {}).forEach(([label, e]) => {
        if (!e || !e.format_id) return;
        const height = Number(e.quality_edge) || Number(e.height) || heightFromLabel(label);
        out.push({
          key: "v:" + e.format_id, family: "video", format: "mp4", formatId: String(e.format_id),
          title: height ? height + "p" : "Original", fps: 0, height,
          sizeMb: positiveNumber(e.size_mb), locked: supporterList && !premium,
        });
      });
      addVideos(data && data.video_formats, false);
      addVideos(data && data.supporter_video_formats, true);
      Object.values((data && data.audio_formats) || {}).forEach((e) => {
        const bitrate = Number(e && e.bitrate);
        if (![128, 256, 320].includes(bitrate)) return;
        out.push({
          key: "a:" + bitrate, family: "audio", format: "mp3", bitrate,
          title: bitrate + " kbps", sizeMb: positiveNumber(e.size_mb),
          locked: !premium && e.tier === "supporter",
        });
      });
    }
    const rank = (c) => (c.family === "video" ? c.height : c.bitrate) || 0;
    out.sort((a, b) => (a.family === b.family ? 0 : a.family === "video" ? -1 : 1) || (rank(a) - rank(b)));
    const seen = new Set();
    return out.filter((c) => (seen.has(c.key) ? false : seen.add(c.key)));
  }


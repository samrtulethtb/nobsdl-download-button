  // ── Presentation helpers (measured numbers only) ───────────────────────
  function formatBytes(bytes) {
    const mb = bytes / (1024 * 1024);
    if (mb >= 1024) return (mb / 1024).toFixed(2) + " GB";
    return (mb >= 100 ? Math.round(mb) : mb.toFixed(1)) + " MB";
  }

  function formatSize(mb) {
    if (!positiveNumber(mb)) return "";
    return "~" + (mb >= 1024 ? (mb / 1024).toFixed(1) + " GB" : (mb < 10 ? mb.toFixed(1) : Math.round(mb)) + " MB");
  }

  function formatSpeed(bps) {
    return bps >= 1024 * 1024 ? (bps / (1024 * 1024)).toFixed(1) + " MB/s" : Math.max(1, Math.round(bps / 1024)) + " KB/s";
  }

  function formatEta(seconds) {
    return seconds < 60 ? t("~{0}s left", Math.max(1, seconds)) : t("~{0} min left", Math.round(seconds / 60));
  }

  function formatDuration(seconds) {
    const s = Math.floor(Number(seconds) || 0);
    if (s <= 0) return "";
    const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
    return h ? h + ":" + String(m).padStart(2, "0") + ":" + String(r).padStart(2, "0") : m + ":" + String(r).padStart(2, "0");
  }

  const PHASE_ORDER = ["requesting", "queued", "connecting", "downloading", "merging", "converting", "finalizing", "ready"];
  const PHASE_STEP = {requesting: 0, queued: 0, connecting: 1, downloading: 1, merging: 2, converting: 2, finalizing: 2, ready: 3};

  function phaseLabel(phase, platformName, format) {
    switch (phase) {
      case "queued": return t("Waiting for a free download slot");
      case "connecting": return t("Connecting to {0}", platformName);
      case "downloading": return t("Downloading on NoBsDL");
      case "merging": return t("Merging video and audio");
      case "converting": return format === "mp3" ? t("Converting to MP3") : t("Processing the file");
      case "finalizing": return t("Finishing up");
      case "ready": return t("Ready");
      default: return t("Starting your download");
    }
  }

  // The bar shows the CURRENT step's measured share: bytes while
  // downloading, our own MP3 encode while converting. Otherwise no number.
  function progressView(phase, progress, elapsedSeconds, platformName, format) {
    const p = progress || {};
    let fraction = typeof p.fraction === "number" ? Math.max(0, Math.min(1, p.fraction)) : null;
    if (phase === "converting") fraction = typeof p.encode_fraction === "number" ? Math.max(0, Math.min(1, p.encode_fraction)) : null;
    let mode = "waiting";
    if (phase === "ready") mode = "done";
    else if ((phase === "downloading" || phase === "converting") && fraction !== null) mode = "measured";
    else if (phase === "merging" || phase === "converting" || phase === "finalizing") mode = "working";

    let text;
    if (phase === "ready") {
      text = t("Ready — your browser is saving the file.");
    } else if (phase === "downloading" && p.downloaded_bytes) {
      const parts = [];
      if (fraction !== null) parts.push(Math.floor(fraction * 100) + "%");
      parts.push(fraction !== null && p.total_bytes
        ? t("{0} of {1}", formatBytes(p.downloaded_bytes), formatBytes(p.total_bytes))
        : t("{0} downloaded", formatBytes(p.downloaded_bytes)));
      if (p.speed_bps) parts.push(formatSpeed(p.speed_bps));
      if (typeof p.eta_seconds === "number" && p.eta_seconds > 0) parts.push(formatEta(p.eta_seconds));
      text = parts.join(" · ");
    } else if (phase === "converting" && fraction !== null) {
      text = phaseLabel(phase, platformName, format) + "… " + Math.floor(fraction * 100) + "%";
    } else {
      text = phaseLabel(phase, platformName, format) + "…" + (elapsedSeconds >= 2 ? " " + elapsedSeconds + "s" : "");
    }
    return {mode, fraction, text, step: PHASE_STEP[phase] || 0};
  }


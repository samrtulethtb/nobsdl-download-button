  function apiGet(path, timeout) {
    const send = gmRequestFunction();
    return new Promise((resolve, reject) => {
      if (!send) {
        reject(Object.assign(new Error("In-page downloads need a userscript manager with GM_xmlhttpRequest."), {status: 0}));
        return;
      }
      const fail = (message) => reject(Object.assign(new Error(message), {status: 0, retryable: true}));
      send({
        method: "GET",
        url: NOBSDL_ORIGIN + path,
        headers: {Accept: "application/json"},
        timeout: timeout || 45000,
        onload: (response) => {
          let data = {};
          try { data = JSON.parse(response.responseText || "{}"); } catch (_) { data = {}; }
          if (!data || typeof data !== "object" || Array.isArray(data)) data = {};
          const status = Number(response.status) || 0;
          if (status >= 200 && status < 300 && data.status !== "error" && data.ok !== false) {
            resolve(data);
            return;
          }
          if (status === 451 && !Object.keys(data).length) {
            reject(Object.assign(new Error(t("NoBsDL isn’t available in your country.")), {status}));
            return;
          }
          reject(Object.assign(new Error(humanMessage(data).slice(0, 300)), {
            status,
            supporterCta: data.supporter_cta === true || data.locked_format === true,
            refreshFormats: /choose_another_quality|retry_format/.test(String(data.suggested_action || "")),
            retryable: status === 429 || status >= 500,
          }));
        },
        onerror: () => fail(t("Can’t reach NoBsDL. Check your connection.")),
        ontimeout: () => fail(t("NoBsDL took too long to answer. Try again.")),
      });
    });
  }


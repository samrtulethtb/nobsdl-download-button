  function normalizeChoices(data) {
    const premium = !!(data && data.is_supporter);
    const out = [];
    const yt = data && data.youtube_video_choices;
    if (yt && (Array.isArray(yt.free) || Array.isArray(yt.supporter))) {
      const addVideo = (c, supporterList) => {
        if (!c || !c.choice_id) return;
        out.push({
          key: "v:" + c.choice_id, family: "video", format: "mp4", ytChoice: String(c.choice_id),
          title: c.height + "p", fps: Number(c.fps) > 30 ? Math.round(Number(c.fps)) : 0,
          height: Number(c.height) || 0, sizeMb: positiveNumber(c.size_mb),
          locked: !premium && (supporterList || c.tier === "supporter"),
        });
      };
      (yt.free || []).forEach((c) => addVideo(c, false));
      (yt.supporter || []).forEach((c) => addVideo(c, true));
      (data.youtube_mp3_choices || []).forEach((c) => {
        if (!c || !c.choice_id) return;
        out.push({
          key: "a:" + c.choice_id, family: "audio", format: "mp3", ytChoice: String(c.choice_id),
          title: c.bitrate_kbps + " kbps", bitrate: Number(c.bitrate_kbps) || 0,
          sizeMb: positiveNumber(c.size_mb), locked: !premium && c.tier === "supporter",
        });
      });
    } else {
      const addVideos = (entries, supporterList) => Object.entries(entries || {}).forEach(([label, e]) => {
        if (!e || !e.format_id) return;
        const height = Number(e.quality_edge) || Number(e.height) || heightFromLabel(label);
        out.push({
          key: "v:" + e.format_id, family: "video", format: "mp4", formatId: String(e.format_id),
          title: height ? height + "p" : "Original", fps: 0, height,
          sizeMb: positiveNumber(e.size_mb), locked: supporterList && !premium,
        });
      });
      addVideos(data && data.video_formats, false);
      addVideos(data && data.supporter_video_formats, true);
      Object.values((data && data.audio_formats) || {}).forEach((e) => {
        const bitrate = Number(e && e.bitrate);
        if (![128, 256, 320].includes(bitrate)) return;
        out.push({
          key: "a:" + bitrate, family: "audio", format: "mp3", bitrate,
          title: bitrate + " kbps", sizeMb: positiveNumber(e.size_mb),
          locked: !premium && e.tier === "supporter",
        });
      });
    }
    const rank = (c) => (c.family === "video" ? c.height : c.bitrate) || 0;
    out.sort((a, b) => (a.family === b.family ? 0 : a.family === "video" ? -1 : 1) || (rank(a) - rank(b)));
    const seen = new Set();
    return out.filter((c) => (seen.has(c.key) ? false : seen.add(c.key)));
  }

